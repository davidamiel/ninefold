import assert from 'node:assert/strict';
import {spokenText} from '../dist/speech-text.js';
assert.equal(spokenText('Article III and Title VII.'),'Article 3 and Title 7.');
assert.equal(spokenText('Chapter CIVIL and Part MIXED.'),'Chapter CIVIL and Part MIXED.');
assert.equal(spokenText('The inter-\nstate\n commerce power.'),'The interstate commerce power.');
assert.equal(spokenText('“Equal protection.”'),'quote, Equal protection, end quote');
assert.equal(spokenText('“A quotation continuing into another passage'),'quote, A quotation continuing into another passage');
assert.equal(spokenText('and ending here.”'),'and ending here, end quote');
assert.equal(spokenText('He said "a fair hearing."'),'He said quote, a fair hearing, end quote');
console.log('Spoken-text normalization checks passed.');
